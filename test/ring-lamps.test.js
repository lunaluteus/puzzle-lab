import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { runInNewContext } from "node:vm";

const page = readFileSync(new URL("../ring-lamps.html", import.meta.url), "utf8");
const rules = page.match(/<script id="ring-lamps-rules">([\s\S]+?)<\/script>/);
assert.ok(rules, "The standalone page must include its ring lamp solvers");
const {optimalPresses, optimalSpacedPresses} = runInNewContext(
  rules[1] + "\n({optimalPresses, optimalSpacedPresses})", {}, {filename: "ring-lamps.html"}
);

function effects(size, offsets) {
  return Array.from({length: size}, (_, press) =>
    offsets.reduce((mask, offset) => mask ^ (1 << ((press + offset) % size)), 0));
}

function pressEffect(presses, windows) {
  return windows.reduce((lights, window, index) => presses & (1 << index) ? lights ^ window : lights, 0);
}

function minimumDistances(windows) {
  const distances = new Int8Array(1 << windows.length).fill(-1);
  const queue = new Int32Array(distances.length);
  distances[0] = 0;
  let tail = 1;
  for (let head = 0; head < tail; head++) {
    const lights = queue[head];
    for (const effect of windows) {
      const next = lights ^ effect;
      if (distances[next] !== -1) continue;
      distances[next] = distances[lights] + 1;
      queue[tail++] = next;
    }
  }
  return distances;
}

function compareWithShortestPaths(windows, solve, rule) {
  const distances = minimumDistances(windows);
  function verify(lights) {
    const presses = solve(lights);
    const expected = distances[lights];
    const context = rule + ", lights " + lights.toString(2);
    if (expected === -1) {
      assert.equal(presses, null, context);
    } else {
      assert.ok(Number.isInteger(presses) && presses >= 0 && presses < distances.length, context);
      assert.equal(pressEffect(presses, windows), lights, context);
      assert.equal([...presses.toString(2)].filter(bit => bit === "1").length, expected, context);
    }
  }

  if (windows.length <= 12) {
    for (let lights = 0; lights < distances.length; lights++) verify(lights);
  } else {
    const fullRing = distances.length - 1;
    verify(fullRing);
    // Sample arbitrary boards and boards generated by valid presses.
    for (let i = 0; i <= 400; i++) {
      verify(Math.imul(i, 0x9e3779b1) & fullRing);
      verify(pressEffect(Math.imul(i, 0x85ebca6b) & fullRing, windows));
    }
  }
  return distances;
}

for (const size of [6, 7, 9, 12, 14, 15, 21]) {
  test("Ring lamps give exact consecutive-press hints for size " + size, () => {
    for (let span = 1; span <= size; span++) {
      const windows = effects(size, Array.from({length: span}, (_, offset) => offset));
      compareWithShortestPaths(windows, lights => optimalPresses(lights, size, span), "span " + span);
    }
  });

  test("Ring lamps give exact spaced-press hints for size " + size, () => {
    const windows = effects(size, [0, 1, 3]);
    const distances = compareWithShortestPaths(windows, lights => optimalSpacedPresses(lights, windows), "spaced");
    if (size === 21) {
      assert.equal(distances.reduce((maximum, distance) => Math.max(maximum, distance), 0), 10);
      assert.equal(distances.reduce((count, distance) => count + Number(distance === 10), 0), 2187);
    }
  });
}
